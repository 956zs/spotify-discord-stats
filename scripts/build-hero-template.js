import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

// Regenerates worker/lib/hero-template-data.js from the hero size template PNG, so the
// Worker can serve it without a static-assets binding. Run after changing the PNG:
//   node scripts/build-hero-template.js
const source = fileURLToPath(new URL('../docs/images/templates/hero-guide-1300x1200.png', import.meta.url));
const target = fileURLToPath(new URL('../worker/lib/hero-template-data.js', import.meta.url));

const bytes = readFileSync(source);
const sha256 = createHash('sha256').update(bytes).digest('hex');
writeFileSync(
  target,
  `// Generated by scripts/build-hero-template.js from docs/images/templates/hero-guide-1300x1200.png.
// Do not edit by hand.
export const HERO_TEMPLATE_SHA256 = '${sha256}';
export const HERO_TEMPLATE_BASE64 =
  '${bytes.toString('base64')}';
`
);
console.log(`wrote ${target} (${bytes.length} bytes, sha256 ${sha256.slice(0, 12)})`);
